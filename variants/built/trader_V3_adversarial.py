# Order book helpers — O(n) over ≤3 levels (effectively O(1))
# ---------------------------------------------------------------------------

def _best_bid(od: Optional[OrderDepth]) -> Tuple[Optional[int], int]:
    if od is None or not od.buy_orders:
        return None, 0
    p = max(od.buy_orders.keys())
    return p, int(od.buy_orders[p])

def _best_ask(od: Optional[OrderDepth]) -> Tuple[Optional[int], int]:
    if od is None or not od.sell_orders:
        return None, 0
    p = min(od.sell_orders.keys())
    return p, int(abs(od.sell_orders[p]))

def _mid(od: Optional[OrderDepth]) -> Optional[float]:
    bp, _ = _best_bid(od); ap, _ = _best_ask(od)
    if bp is None or ap is None:
        return None
    return (bp + ap) / 2.0


